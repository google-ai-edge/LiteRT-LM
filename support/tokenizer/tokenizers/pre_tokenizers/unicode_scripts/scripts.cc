Script GetScript(char32_t c) {
  const uint32_t cp = static_cast<uint32_t>(c);
  // First range whose `hi` is >= cp; it matches iff its `lo` is <= cp.
  const ScriptRange* it =
      std::lower_bound(std::begin(kScriptRanges), std::end(kScriptRanges), cp,
                       [](const ScriptRange& range, uint32_t value) {
                         return range.hi < value;
                       });
  if (it != std::end(kScriptRanges) && it->lo <= cp) {
    return it->script;
  }
  return Script::kAny;
}


GraphemeCatRange GraphemeCategory(char32_t c) {
  const absl::Span<const uint16_t> grapheme_cat_lookup =
      absl::MakeConstSpan(kGraphemeCatLookupData);
  const absl::Span<const GraphemeCatEntry> grapheme_cat_table =
      absl::MakeConstSpan(kGraphemeCatTableData);
  // Perform a quick O(1) lookup in a precomputed table to determine
  // the slice of the range table to search in.
  const uint32_t lookup_interval = 128;
  const size_t idx = static_cast<uint32_t>(c) / lookup_interval;
  size_t range_start;
  size_t range_end;
  if (idx + 2 <= grapheme_cat_lookup.size()) {
    range_start = grapheme_cat_lookup[idx];
    range_end = grapheme_cat_lookup[idx + 1] + 1;
  } else {
    // If the `idx` is outside of the precomputed table - use the slice
    // starting from the last covered index in the precomputed table and
    // ending with the length of the range table.
    range_start = 1612;
    range_end = 1618;
  }

  // Compute pessimistic default lower and upper bounds on the category.
  // If character doesn't map to any range and there is no adjacent range
  // in the table slice - these bounds has to apply.
  const uint32_t lower = static_cast<uint32_t>(idx) * lookup_interval;
  const uint32_t upper = lower + lookup_interval - 1;
  return BsearchRangeValueTable(
      c, grapheme_cat_table.subspan(range_start, range_end - range_start),
      lower, upper);
}


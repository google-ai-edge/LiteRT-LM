def fmt_items(items, per_line, indent='    '):
  lines = []
  for i in range(0, len(items), per_line):
    lines.append(indent + ' '.join(x + ',' for x in items[i : i + per_line]))
  return '\n'.join(lines)


def cpp_array(ctype, name, items, per_line, static=True):
  """`static const T kNameData[] = { ... };` (preformatted item strings)."""
  prefix = 'static ' if static else ''
  if not items:
    # Zero-length arrays are not valid C++; the users of an empty table use an
    # empty span instead (see cpp_span).
    return ''
  return '%sconst %s %sData[%d] = {\n%s\n};\n' % (
      prefix,
      ctype,
      name,
      len(items),
      fmt_items(items, per_line),
  )


def cpp_span(ctype, name, count):
  if count == 0:
    return 'const absl::Span<const %s> %s;\n' % (ctype, name)
  return 'const absl::Span<const %s> %s = absl::MakeConstSpan(%sData);\n' % (
      ctype,
      name,
      name,
  )


def hex32(v):
  return '0x%04X' % v


def cpp_string_literal(s):
  """Encodes a Python string as a C++ narrow string literal of its UTF-8."""
  raw = s.encode('utf-8')
  out = ['"']
  for b in raw:
    if b == 0x22:
      out.append('\\"')
    elif b == 0x5C:
      out.append('\\\\')
    elif 0x20 <= b < 0x7F:
      out.append(chr(b))
    else:
      # Octal escapes are at most three digits long, so a following digit is
      # never misparsed as part of the escape (unlike with \x escapes).
      out.append('\\%03o' % b)
  out.append('"')
  lit = ''.join(out)
  if 0 in raw:
    return 'std::string(%s, %d)' % (lit, len(raw))
  return lit


def write(path, content):
  with open(path, 'w') as f:
    f.write(content)
  print('wrote', path)


def guard(basename):
  return GUARD_PREFIX + basename.upper().replace('.', '_') + '_'


def rel(path):
  """The repository-relative basename of a source file, for provenance comments."""
  return os.path.basename(path)



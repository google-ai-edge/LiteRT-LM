def parse_test_cases(body, strings_per_case):
  """Parses `("input", &["a", "b"], ...)` tuples into lists of string lists."""
  cases = []
  # Split on top-level tuples: each starts with `("` and the previous one ends
  # with `])`. Tokenizing the whole body and re-grouping by the `&[` markers is
  # simpler: walk the raw text and collect string tokens per tuple.
  depth = 0
  current = None
  i = 0
  while i < len(body):
    c = body[i]
    if c == '"':
      m = re.compile(r'"(?:\\.|[^"\\])*"').match(body, i)
      current[-1].append(parse_string_literal(m.group(0)[1:-1]))
      i = m.end()
      continue
    if c == '(' and depth == 0:
      current = [[]]
    elif c == '[':
      current.append([])
    elif c == ')' and depth == 1:
      assert len(current) == strings_per_case, current
      assert len(current[0]) == 1
      cases.append([current[0][0]] + current[1:])
    if c in '([':
      depth += 1
    elif c in ')]':
      depth -= 1
    i += 1
  return cases



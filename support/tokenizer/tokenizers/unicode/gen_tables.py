def parse_l1_lut(text, name):
  """Parses `static NAME: L1Lut = L1Lut { l2_luts: [ L2Lut {...}, ... ] };`.

  Returns a list (one per plane) of (singles, multis, exceptions) where
  singles = [(start, len, parity, delta)], multis = [(key, (o0, o1, o2))],
  exceptions = [(key, (c0, c1, c2))].
  """
  body = extract_block(
      text, r'static ' + name + r': L1Lut = L1Lut \{', r'\n    \};'
  )
  planes = []
  for l2 in re.split(r'L2Lut \{', body)[1:]:
    singles_text = extract_block(l2, r'singles: &\[', r'\n\s*\],')
    multis_text = extract_block(l2, r'multis: &\[', r'\n\s*\],')
    exceptions_text = extract_block(l2, r'exceptions: &\[', r'\n\s*\],')
    singles = []
    for kind, start, end, delta in _SINGLE_RE.findall(singles_text):
      start = int(start, 16)
      end = int(end, 16) if end else start
      assert start <= end and end - start <= 255
      parity = kind == 'step_by_2'
      singles.append((start, end - start, parity, int(delta)))
    multis = [
        (m[0], (m[1], m[2], m[3])) for m in grouped(numbers(multis_text), 4)
    ]
    exceptions = []
    for key, c0, c1, c2 in grouped(values(exceptions_text, ('num', 'char')), 4):
      exceptions.append((key, (c0, c1, c2)))
    planes.append((singles, multis, exceptions))
  assert len(planes) == 2, len(planes)
  return planes



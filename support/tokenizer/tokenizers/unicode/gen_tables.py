_SIMPLE_ESCAPES = {
    'n': '\n',
    'r': '\r',
    't': '\t',
    '\\': '\\',
    '0': '\0',
    "'": "'",
    '"': '"',
}


def parse_char_literal(text):
  """Parses the contents of a Rust char literal (without the quotes)."""
  if text.startswith('\\u{'):
    return int(text[3:-1], 16)
  if text.startswith('\\x'):
    return int(text[2:], 16)
  if text.startswith('\\'):
    return ord(_SIMPLE_ESCAPES[text[1]])
  assert len(text) == 1, text
  return ord(text)


def parse_string_literal(text):
  """Parses the contents of a Rust string literal (without the quotes)."""
  out = []
  i = 0
  while i < len(text):
    c = text[i]
    if c != '\\':
      out.append(c)
      i += 1
      continue
    nxt = text[i + 1]
    if nxt == 'u':
      end = text.index('}', i)
      out.append(chr(int(text[i + 3 : end], 16)))
      i = end + 1
    elif nxt == 'x':
      out.append(chr(int(text[i + 2 : i + 4], 16)))
      i += 4
    else:
      out.append(_SIMPLE_ESCAPES[nxt])
      i += 2
  return ''.join(out)


_TOKEN_RE = re.compile(
    r"""
    (?P<comment>//[^\n]*) |
    (?P<char>'(?:\\u\{[0-9A-Fa-f]+\}|\\x[0-9A-Fa-f]{2}|\\.|[^'\\])') |
    (?P<string>"(?:\\.|[^"\\])*") |
    (?P<num>-?0x[0-9A-Fa-f_]+|-?[0-9][0-9_]*) |
    (?P<ident>[A-Za-z_][A-Za-z0-9_]*)
    """,
    re.VERBOSE,
)


def tokenize(text):
  """Yields (kind, value) tokens of a Rust table body; punctuation is skipped."""
  for m in _TOKEN_RE.finditer(text):
    kind = m.lastgroup
    if kind == 'comment':
      continue
    val = m.group(kind)
    if kind == 'char':
      yield ('char', parse_char_literal(val[1:-1]))
    elif kind == 'string':
      yield ('string', parse_string_literal(val[1:-1]))
    elif kind == 'num':
      val = val.replace('_', '')
      yield ('num', int(val, 16) if 'x' in val else int(val, 10))
    else:
      yield ('ident', val)


def extract_block(text, start_pattern, end_pattern):
  """Returns the text between the first match of `start_pattern` (exclusive)

  and the first match of `end_pattern` after it (exclusive).
  """
  m = re.search(start_pattern, text)
  if not m:
    raise ValueError('pattern not found: %r' % start_pattern)
  rest = text[m.end() :]
  e = re.search(end_pattern, rest)
  if not e:
    raise ValueError('end pattern not found: %r' % end_pattern)
  return rest[: e.start()]


def extract_const_body(text, name):
  """Returns the body of `const NAME: ... = &[ ... ];` (or `static`/`[..]`)."""
  return extract_block(
      text,
      r'(?:const|static)\s+' + re.escape(name) + r'\s*:[^=\n]*=\s*&?\[',
      r'\]\s*;',
  )


def numbers(text):
  return [v for k, v in tokenize(text) if k == 'num']


def chars(text):
  return [v for k, v in tokenize(text) if k == 'char']


def values(text, kinds):
  """Returns the token values of the given kinds, in order."""
  return [v for k, v in tokenize(text) if k in kinds]


def grouped(seq, n):
  assert len(seq) % n == 0, (len(seq), n)
  return [tuple(seq[i : i + n]) for i in range(0, len(seq), n)]


def unicode_version(text):
  m = re.search(
      r'UNICODE_VERSION:\s*\(u\d+,\s*u\d+,\s*u\d+\)\s*=\s*'
      r'\((\d+),\s*(\d+),\s*(\d+)\)',
      text,
  )
  return '%s.%s.%s' % m.groups() if m else 'unknown'



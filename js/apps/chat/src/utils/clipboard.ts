/**
 * Copies plain text to the system clipboard, falling back cleanly to a
 * temporary offscreen textarea when `navigator.clipboard` is unavailable (for
 * example on non-HTTPS devserver hostnames).
 */
export async function copyToClipboard(text: string): Promise<void> {
  if (navigator.clipboard?.writeText) {
    await navigator.clipboard.writeText(text);
    return;
  }

  const textarea = document.createElement('textarea');
  textarea.value = text;
  textarea.setAttribute('readonly', '');
  textarea.style.position = 'fixed';
  textarea.style.top = '-9999px';
  textarea.style.left = '-9999px';
  textarea.style.opacity = '0';
  document.body.appendChild(textarea);
  textarea.select();
  try {
    const ok = document.execCommand('copy');
    if (!ok) {
      throw new Error('Fallback copy command returned false.');
    }
  } finally {
    textarea.remove();
  }
}

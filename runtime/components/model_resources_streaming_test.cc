TEST(ModelResourcesStreamingTest,
     AddTFLiteModelBufferTwiceReturnsModelFromNewBuffer) {
  ModelResourcesStreaming model_resources;

  std::string model1_str(reinterpret_cast<const char*>(kDummyModel1),
                         sizeof(kDummyModel1));
  std::string model2_str(reinterpret_cast<const char*>(kDummyModel2),
                         sizeof(kDummyModel2));

  // Add the first buffer using rvalue move overload.
  ASSERT_OK(model_resources.AddTFLiteModelBuffer(
      ModelType::kTfLiteVisionEncoder, std::move(model1_str)));

  auto model1_or =
      model_resources.GetTFLiteModel(ModelType::kTfLiteVisionEncoder);
  ASSERT_OK(model1_or);
  const litert::Model* model1_ptr = *model1_or;
  ASSERT_NE(model1_ptr, nullptr);
  auto input_names1_or = model1_ptr->GetSignatureInputNames("serving_default");
  ASSERT_TRUE(input_names1_or.HasValue());
  ASSERT_EQ(input_names1_or->size(), 1);
  EXPECT_EQ((*input_names1_or)[0], "features");

  auto buf1_or =
      model_resources.GetTFLiteModelBuffer(ModelType::kTfLiteVisionEncoder);
  ASSERT_OK(buf1_or);
  EXPECT_EQ(buf1_or->size(), sizeof(kDummyModel1));

  // Add the second buffer for the same ModelType.
  ASSERT_OK(model_resources.AddTFLiteModelBuffer(
      ModelType::kTfLiteVisionEncoder, std::move(model2_str)));

  auto buf2_or =
      model_resources.GetTFLiteModelBuffer(ModelType::kTfLiteVisionEncoder);
  ASSERT_OK(buf2_or);
  EXPECT_EQ(buf2_or->size(), sizeof(kDummyModel2));
  EXPECT_EQ(std::string_view(buf2_or->data(), buf2_or->size()),
            std::string_view(reinterpret_cast<const char*>(kDummyModel2),
                             sizeof(kDummyModel2)));

  // GetTFLiteModel must return a model built from the new buffer.
  auto model2_or =
      model_resources.GetTFLiteModel(ModelType::kTfLiteVisionEncoder);
  ASSERT_OK(model2_or);
  const litert::Model* model2_ptr = *model2_or;
  ASSERT_NE(model2_ptr, nullptr);
  auto input_names2_or = model2_ptr->GetSignatureInputNames("serving_default");
  ASSERT_TRUE(input_names2_or.HasValue());
  ASSERT_EQ(input_names2_or->size(), 1);
  EXPECT_EQ((*input_names2_or)[0], "src_inputs");
}

TEST(ModelResourcesStreamingTest,
     ReleaseTFLiteModelBufferClearsModelAndBuffer) {
  ModelResourcesStreaming model_resources;

  std::string model_str(reinterpret_cast<const char*>(kDummyModel1),
                        sizeof(kDummyModel1));

  ASSERT_OK(model_resources.AddTFLiteModelBuffer(
      ModelType::kTfLiteEndOfVision, std::move(model_str)));

  // Verify buffer is present and model can be instantiated.
  auto buf_or =
      model_resources.GetTFLiteModelBuffer(ModelType::kTfLiteEndOfVision);
  ASSERT_OK(buf_or);
  EXPECT_EQ(buf_or->size(), sizeof(kDummyModel1));

  auto model_or =
      model_resources.GetTFLiteModel(ModelType::kTfLiteEndOfVision);
  ASSERT_OK(model_or);
  ASSERT_NE(*model_or, nullptr);

  // Release the model buffer and cached model.
  model_resources.ReleaseTFLiteModelBuffer(ModelType::kTfLiteEndOfVision);

  // Subsequent calls must return NotFoundError.
  EXPECT_EQ(model_resources.GetTFLiteModel(ModelType::kTfLiteEndOfVision)
                .status()
                .code(),
            absl::StatusCode::kNotFound);
  EXPECT_EQ(
      model_resources.GetTFLiteModelBuffer(ModelType::kTfLiteEndOfVision)
          .status()
          .code(),
      absl::StatusCode::kNotFound);

  // Releasing a non-existent or already-released buffer is a safe no-op.
  model_resources.ReleaseTFLiteModelBuffer(ModelType::kTfLiteEndOfVision);
  model_resources.ReleaseTFLiteModelBuffer(ModelType::kUnknown);
}

